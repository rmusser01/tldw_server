async def deliver(
    harness: SimpleNamespace,
    *,
    backoff: int = 0,
    bind_completion_token: bool = False,
) -> dict[str, Any]:
    """Let the real SDK acquire, execute and durably settle exactly one delivery."""
    sdk = WorkerSDK(
        harness.jobs,
        WorkerConfig(
            domain="vn_assets",
            queue=vn_asset_generation_jobs_queue(),
            worker_id="pr3071-finite-worker",
            lease_seconds=120,
            retry_backoff_seconds=backoff,
            bind_completion_token=bind_completion_token,
        ),
    )
    deliveries: list[dict[str, Any]] = []

    async def handle(job: dict[str, Any]) -> dict[str, Any]:
        deliveries.append(dict(job))
        try:
            return await harness.worker.handle_job_async(job)
        finally:
            sdk.stop()

    await asyncio.wait_for(sdk.run(handler=handle, job_type="vn_asset_generate_variant"), timeout=5)
    assert len(deliveries) == 1
    return deliveries[0]


async def test_runtime_error_retries_v1_before_terminalizing(lifecycle: SimpleNamespace) -> None:
    """A transient adapter error keeps V1 active until the actual Jobs retry succeeds."""

    class OnceFailingAdapter(FakeImageAdapter):
        def generate(self, request: Any) -> Any:
            if not self.requests:
                self.requests.append(request)
                raise RuntimeError("finite transient error")
            return super().generate(request)

    adapter = OnceFailingAdapter()
    lifecycle.worker.image_registry = FakeImageRegistry(adapter)
    batch_id = lifecycle.start()
    first = await deliver(lifecycle)
    stored = lifecycle.jobs.get_job(first["id"])
    assert first["retry_count"] == 0 and first["max_retries"] == 1
    assert stored["status"] == "queued" and stored["retry_count"] == 1
    assert lifecycle.repo.get_variant_outcome(batch_id, lifecycle.slot.id, 0)["outcome_status"] == "planned"
    second = await deliver(lifecycle)
    assert second["id"] == first["id"] and second["retry_count"] == 1
    assert lifecycle.jobs.get_job(second["id"])["status"] == "completed"
    assert lifecycle.repo.get_batch(batch_id)["status"] == "completed"
    assert len(adapter.requests) == 2


