@pytest.mark.parametrize("boundary", ["attachment", "publication"])
async def test_exhausted_storage_reconciliation_fails_without_deleting_recoverable_bytes(
    lifecycle: SimpleNamespace,
    monkeypatch: pytest.MonkeyPatch,
    boundary: str,
) -> None:
    """An exhausted handoff is a retryable failed batch, not a permanently active claim."""

    def unavailable(*_args: Any, **_kwargs: Any) -> None:
        raise RuntimeError("finite settlement outage")

    monkeypatch.setattr(
        lifecycle.repo, "update_item_storage" if boundary == "attachment" else "complete_variant", unavailable
    )
    batch_id = lifecycle.start()
    first = await deliver(lifecycle)
    assert lifecycle.jobs.get_job(first["id"])["status"] == "queued"
    assert lifecycle.repo.get_batch(batch_id)["status"] != "failed"
    records = dict(lifecycle.storage.records)
    second = await deliver(lifecycle)
    assert second["id"] == first["id"] and second["retry_count"] == 1
    assert lifecycle.jobs.get_job(first["id"])["status"] == "failed"
    assert lifecycle.repo.get_batch(batch_id)["status"] == "failed"
    assert lifecycle.repo.get_variant_outcome(batch_id, lifecycle.slot.id, 0)["outcome_status"] == "failed"
    assert lifecycle.storage.records == records
    assert lifecycle.storage.usage == len(b"fake-png")
    assert [path.read_bytes() for path in lifecycle.outputs.glob("generated-*.png")] == [b"fake-png"]
    assert len(lifecycle.adapter.requests) == 1
    assert lifecycle.service.retry_slot(lifecycle.pack.id, lifecycle.slot.id).source_batch_id == batch_id


async def test_service_queued_retry_does_not_run_terminal_callback(
    lifecycle: SimpleNamespace,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """The production callback wiring leaves an ordinary queued retry active."""
    monkeypatch.setenv("JOBS_QUARANTINE_THRESHOLD", "2")

    class FailingAdapter(FakeImageAdapter):
        def generate(self, request: Any) -> Any:
            self.requests.append(request)
            raise RuntimeError("finite queued retry")

    async def unexpected_callback(*_args: Any, **_kwargs: Any) -> None:
        pytest.fail("queued work must not invoke the terminal callback")

    lifecycle.worker.image_registry = FakeImageRegistry(FailingAdapter())
    monkeypatch.setattr(service_worker, "handle_vn_asset_failed_job", unexpected_callback)
    batch_id = lifecycle.start()
    acquired = await deliver_service(lifecycle, monkeypatch)
    stored = lifecycle.jobs.get_job(acquired["id"])
    assert stored["status"] == "queued" and stored["completion_token"] is None
    assert lifecycle.repo.get_batch(batch_id)["status"] == "enqueued"
    outcome = lifecycle.repo.get_variant_outcome(batch_id, lifecycle.slot.id, 0)
    assert outcome["outcome_status"] == "planned" and outcome["claim_lease_id"] == acquired["lease_id"]


async def quarantined_claim(
    harness: SimpleNamespace,
    monkeypatch: pytest.MonkeyPatch,
) -> tuple[int, dict[str, Any]]:
    """Retain a real terminal Jobs row before invoking its VN callback."""
    monkeypatch.setenv("JOBS_QUARANTINE_THRESHOLD", "1")

    class FailingAdapter(FakeImageAdapter):
        def generate(self, request: Any) -> Any:
            self.requests.append(request)
            raise RuntimeError("finite terminal disposition")

    harness.worker.image_registry = FakeImageRegistry(FailingAdapter())
    batch_id = harness.start()
    acquired = await deliver(harness, bind_completion_token=True)
    stored = harness.jobs.get_job(acquired["id"])
    assert stored["status"] == "quarantined" and stored["completion_token"] == acquired["lease_id"]
    assert harness.repo.get_variant_outcome(batch_id, harness.slot.id, 0)["outcome_status"] == "planned"
    return batch_id, acquired


@pytest.mark.parametrize(
    ("field", "replacement"),
    [
        ("uuid", "foreign-uuid"),
        ("owner_user_id", "2"),
        ("domain", "foreign-domain"),
        ("queue", "foreign-queue"),
        ("job_type", "foreign-type"),
        ("batch_group", "foreign-batch"),
        ("idempotency_key", "foreign-key"),
        ("completion_token", "other-delivery"),
        ("id", -1),
        ("payload", {"user_id": 2}),
        ("status", "queued"),
        ("status", "processing"),
        ("status", "completed"),
        ("status", "cancelled"),
    ],
)
async def test_terminal_callback_rejects_changed_jobs_authority(
    lifecycle: SimpleNamespace,
    monkeypatch: pytest.MonkeyPatch,
    field: str,
    replacement: Any,
) -> None:
    """A terminal Jobs read is not authority unless every delivery fence still matches."""
    batch_id, acquired = await quarantined_claim(lifecycle, monkeypatch)
    original_read = lifecycle.jobs.get_job_or_archived_by_uuid
    before_batch = lifecycle.repo.get_batch(batch_id)
    before_outcome = lifecycle.repo.get_variant_outcome(batch_id, lifecycle.slot.id, 0)

    def changed_read(*args: Any, **kwargs: Any) -> dict[str, Any]:
        stored = dict(original_read(*args, **kwargs))
        stored[field] = replacement
        return stored

    monkeypatch.setattr(lifecycle.jobs, "get_job_or_archived_by_uuid", changed_read)
    await lifecycle.worker.handle_failed_job(acquired, RuntimeError("delayed callback"))
    assert lifecycle.repo.get_batch(batch_id) == before_batch
    assert lifecycle.repo.get_variant_outcome(batch_id, lifecycle.slot.id, 0) == before_outcome


async def test_terminal_callback_rechecks_claim_under_write_admission(
    lifecycle: SimpleNamespace,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Cancellation between callback preparation and VN admission cannot be overwritten."""
    batch_id, acquired = await quarantined_claim(lifecycle, monkeypatch)
    original_fail = lifecycle.repo.fail_variant

    def cancel_before_admission(**kwargs: Any) -> None:
        lifecycle.repo.cancel_batch(batch_id)
        original_fail(**kwargs)

    monkeypatch.setattr(lifecycle.repo, "fail_variant", cancel_before_admission)
    with pytest.raises(VNAssetGenerationError, match="vn_asset_job_lease_lost"):
        await lifecycle.worker.handle_failed_job(acquired, RuntimeError("delayed callback"))
    current = lifecycle.repo.get_variant_outcome(batch_id, lifecycle.slot.id, 0)
    assert current["outcome_status"] == "cancelled"
    assert lifecycle.repo.get_batch(batch_id)["status"] == "cancelled"


async def test_terminal_callback_rejects_a_newer_claim(
    lifecycle: SimpleNamespace,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A real later Jobs acquisition and V1 takeover retire the old callback authority."""
    monkeypatch.setenv("JOBS_QUARANTINE_THRESHOLD", "2")

    class FailingAdapter(FakeImageAdapter):
        def generate(self, request: Any) -> Any:
            self.requests.append(request)
            raise RuntimeError("finite retry before takeover")

    lifecycle.worker.image_registry = FakeImageRegistry(FailingAdapter())
    batch_id = lifecycle.start()
    first = await deliver(lifecycle, bind_completion_token=True)
    second = lifecycle.jobs.acquire_next_job(
        domain="vn_assets",
        queue=vn_asset_generation_jobs_queue(),
        worker_id="new-owner",
        lease_seconds=120,
        job_type="vn_asset_generate_variant",
    )
    assert second["id"] == first["id"] and second["lease_id"] != first["lease_id"]
    old_outcome = lifecycle.repo.get_variant_outcome(batch_id, lifecycle.slot.id, 0)
    lifecycle.repo.claim_variant(
        batch_id=batch_id,
        slot_id=lifecycle.slot.id,
        variant_index=0,
        lease_id=second["lease_id"],
        attempt_token=uuid4().hex,
        item_fields={},
        allow_takeover=True,
        expected_claim_token=old_outcome["claim_token"],
        validate_authority=lambda: lifecycle.worker._require_current_job_lease(second, user_id=1),
    )
    before = lifecycle.repo.get_variant_outcome(batch_id, lifecycle.slot.id, 0)
    await lifecycle.worker.handle_failed_job(first, RuntimeError("old callback"))
    assert lifecycle.repo.get_variant_outcome(batch_id, lifecycle.slot.id, 0) == before
    assert lifecycle.repo.get_batch(batch_id)["status"] == "enqueued"


