@pytest.mark.parametrize("unlink_outage", [False, True])
async def test_cancelled_sibling_storage_is_cleaned_before_queued_delivery_is_cancelled(
    lifecycle: SimpleNamespace,
    monkeypatch: pytest.MonkeyPatch,
    unlink_outage: bool,
) -> None:
    """A different child cannot cancel the sole retry path for a charged hidden reservation."""
    original_attach = lifecycle.repo.update_item_storage

    def unavailable(*_args: Any, **_kwargs: Any) -> None:
        raise RuntimeError("finite attachment outage")

    monkeypatch.setattr(lifecycle.repo, "update_item_storage", unavailable)
    batch_id = lifecycle.start(variant_count=2)
    first = await deliver(lifecycle, backoff=60)
    assert lifecycle.jobs.get_job(first["id"])["status"] == "queued"
    assert lifecycle.storage.usage == len(b"fake-png")
    monkeypatch.setattr(lifecycle.repo, "update_item_storage", original_attach)
    lifecycle.repo.cancel_batch(batch_id)
    terminal_batch = lifecycle.repo.get_batch(batch_id)
    original_unlink = worker_module.unlink_vn_asset_storage_file
    if unlink_outage:

        def unavailable_unlink(**_kwargs: Any) -> bool:
            raise PermissionError("finite unlink outage")

        monkeypatch.setattr(worker_module, "unlink_vn_asset_storage_file", unavailable_unlink)
    sibling = await deliver(lifecycle)
    assert sibling["id"] != first["id"]
    if unlink_outage:
        assert lifecycle.jobs.get_job(first["id"])["status"] == "queued"
        assert lifecycle.jobs.get_job(sibling["id"])["status"] == "queued"
        assert lifecycle.storage.usage == len(b"fake-png")
        monkeypatch.setattr(worker_module, "unlink_vn_asset_storage_file", original_unlink)
        assert (await deliver(lifecycle))["id"] == sibling["id"]
    assert lifecycle.jobs.get_job(first["id"])["status"] == "cancelled"
    assert lifecycle.storage.records == {}
    assert lifecycle.storage.usage == 0
    assert len(lifecycle.storage.removed) == 1
    assert list(lifecycle.outputs.glob("generated-*.png")) == []
    assert len(lifecycle.adapter.requests) == 1
    assert lifecycle.repo.get_batch(batch_id) == terminal_batch
    assert (
        lifecycle.jobs.acquire_next_job(
            domain="vn_assets",
            queue=vn_asset_generation_jobs_queue(),
            worker_id="no-redelivery",
            lease_seconds=120,
            job_type="vn_asset_generate_variant",
        )
        is None
    )


async def deliver_service(
    harness: SimpleNamespace,
    monkeypatch: pytest.MonkeyPatch,
) -> dict[str, Any]:
    """Run the real production SDK wiring with a finite injected generation handler."""
    deliveries: list[dict[str, Any]] = []
    sdks: list[WorkerSDK] = []

    def sdk_factory(manager: JobManager, config: WorkerConfig) -> WorkerSDK:
        sdk = WorkerSDK(manager, config)
        sdks.append(sdk)
        return sdk

    async def handle(job: dict[str, Any], **_kwargs: Any) -> dict[str, Any]:
        deliveries.append(dict(job))
        try:
            return await harness.worker.handle_job_async(job)
        finally:
            sdks[0].stop()

    async def own_db(owner: int, **_kwargs: Any) -> CharactersRAGDB:
        assert owner == 1
        return harness.repo.db

    monkeypatch.setattr(service_worker, "JobManager", lambda: harness.jobs)
    monkeypatch.setattr(service_worker, "WorkerSDK", sdk_factory)
    monkeypatch.setattr(service_worker, "handle_vn_asset_job", handle)
    monkeypatch.setattr(service_worker, "get_chacha_db_for_user_id", own_db)
    await asyncio.wait_for(service_worker.run_vn_asset_generation_jobs_worker(), timeout=5)
    assert len(deliveries) == 1
    return deliveries[0]


@pytest.mark.parametrize("boundary", ["runtime", "explicit", "attachment", "publication"])
async def test_first_delivery_quarantine_terminalizes_exact_v1_claim(
    lifecycle: SimpleNamespace,
    monkeypatch: pytest.MonkeyPatch,
    boundary: str,
) -> None:
    """Verified Jobs quarantine must settle V1 even before its retry budget is spent."""
    monkeypatch.setenv("JOBS_QUARANTINE_THRESHOLD", "1")

    class FailingAdapter(FakeImageAdapter):
        def generate(self, request: Any) -> Any:
            self.requests.append(request)
            if boundary == "explicit":
                raise VNAssetGenerationError("finite quarantine error", retryable=True)
            raise RuntimeError("finite quarantine error")

    def unavailable(*_args: Any, **_kwargs: Any) -> None:
        raise RuntimeError("finite quarantine handoff outage")

    if boundary in {"runtime", "explicit"}:
        lifecycle.worker.image_registry = FakeImageRegistry(FailingAdapter())
    else:
        monkeypatch.setattr(
            lifecycle.repo,
            "update_item_storage" if boundary == "attachment" else "complete_variant",
            unavailable,
        )
    batch_id = lifecycle.start()
    acquired = await deliver_service(lifecycle, monkeypatch)
    stored = lifecycle.jobs.get_job(acquired["id"])
    assert acquired["retry_count"] == 0 and acquired["max_retries"] == 1
    assert stored["status"] == "quarantined"
    assert stored["retry_count"] == 1 and stored["lease_id"] is None
    assert lifecycle.repo.get_batch(batch_id)["status"] == "failed"
    assert lifecycle.repo.get_variant_outcome(batch_id, lifecycle.slot.id, 0)["outcome_status"] == "failed"
    assert lifecycle.repo.get_slot(lifecycle.slot.id)["status"] == "failed"
    if boundary in {"attachment", "publication"}:
        assert lifecycle.storage.usage == len(b"fake-png")
        assert len(lifecycle.storage.records) == 1
        assert [p.read_bytes() for p in lifecycle.outputs.glob("generated-*.png")] == [b"fake-png"]
    else:
        assert lifecycle.storage.records == {}
    assert lifecycle.service.retry_slot(lifecycle.pack.id, lifecycle.slot.id).source_batch_id == batch_id
