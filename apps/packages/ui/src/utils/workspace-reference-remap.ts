import type { WorkspaceExportBundle } from "@/store/workspace-bundle"
import { sanitizeImportedChatSession } from "@/store/workspace-bundle"
import type { WorkspaceNote } from "@/types/workspace"
import { readWorkspaceArtifactClientPayload } from "@/store/workspace-artifact-codec"
import {
  resolveKnowledgeNoteProvenance,
  retainKnowledgeNoteProvenance,
  validateKnowledgeNoteProvenance,
  type KnowledgeNoteProvenance
} from "./knowledge-note-provenance"

export type VerifiedResearchImportMaps = {
  media: Record<string, number | null>
  notes: Record<string, string | null>
}
export type PortableWorkspaceIdentity = { id: string; name: string; tag: string }
const record = (value: unknown): value is Record<string, unknown> =>
  value !== null && typeof value === "object" && !Array.isArray(value)
const clone = <T,>(value: T): T => JSON.parse(JSON.stringify(value))

const mappedMedia = (value: unknown, maps: VerifiedResearchImportMaps): number => {
  const mapped = maps.media[String(value)]
  if (!Number.isSafeInteger(mapped) || Number(mapped) <= 0)
    throw new Error(`Missing or ambiguous Media mapping for ${String(value)}.`)
  return mapped as number
}
const mappedNote = (value: unknown, maps: VerifiedResearchImportMaps): string => {
  const mapped = maps.notes[String(value)]
  if (typeof mapped !== "string" || !mapped.trim())
    throw new Error(`Missing or ambiguous Note mapping for ${String(value)}.`)
  return mapped
}

/** Only known reference fields change. Text, offsets, page labels and evidence IDs are historical data. */
const remapReferences = (
  value: unknown,
  maps: VerifiedResearchImportMaps,
  sourceIds: Record<string, string>,
  workspaceId: string
): unknown => {
  if (Array.isArray(value)) return value.map(item => remapReferences(item, maps, sourceIds, workspaceId))
  if (!record(value)) return value
  const output: Record<string, unknown> = Object.create(null)
  const sourceType = String(value.sourceType ?? value.source_type ?? value.source ?? "").toLowerCase()
  const sourceReference = (id: unknown): unknown => {
    if (sourceIds[String(id)]) return sourceIds[String(id)]
    if (["notes_db", "notes", "note"].includes(sourceType)) return mappedNote(id, maps)
    if (["media", "media_db", "pdf", "document"].includes(sourceType) || /^\d+$/.test(String(id))) {
      const mapped = mappedMedia(id, maps)
      return typeof id === "string" ? String(mapped) : mapped
    }
    throw new Error(`Unresolved source reference: ${String(id)}.`)
  }
  for (const [key, item] of Object.entries(value)) {
    // Chunk IDs and live request/chat ownership are generated by the destination.
    if (["chunkId", "chunk_id", "serverMessageId", "server_message_id", "serverChatId", "historyId", "captureOwnerScope"].includes(key)) continue
    if (["mediaId", "media_id", "mediaID", "snapshotMediaId"].includes(key) && item != null) {
      output[key] = mappedMedia(item, maps)
    } else if (key === "originalId" && item != null && ["notes_db", "notes", "note"].includes(sourceType)) {
      output[key] = mappedNote(item, maps)
    } else if (key === "originalId" && value.mediaId != null && String(item) === String(value.mediaId)) {
      output[key] = mappedMedia(item, maps)
    } else if (key === "include_media_ids" && Array.isArray(item)) {
      output[key] = item.map(id => mappedMedia(id, maps))
    } else if (key === "include_note_ids" && Array.isArray(item)) {
      output[key] = item.map(id => mappedNote(id, maps))
    } else if (["sourceId", "source_id"].includes(key) && item != null) {
      output[key] = sourceReference(item)
    } else if (["source_ids", "selectedSourceIds"].includes(key) && Array.isArray(item)) {
      output[key] = item.map(sourceReference)
    } else if (key === "workspace_id") {
      output[key] = workspaceId
    } else {
      output[key] = remapReferences(item, maps, sourceIds, workspaceId)
    }
  }
  return output
}

export const remapPortableNote = (
  note: WorkspaceNote,
  maps: VerifiedResearchImportMaps,
  identity: PortableWorkspaceIdentity
): WorkspaceNote => {
  const output = clone(note)
  output.content = retainKnowledgeNoteProvenance(note.content, note)
  if (note.id != null) output.id = mappedNote(note.id, maps)
  const provenance = resolveKnowledgeNoteProvenance(note, note.content).provenance
  const remapProvenance = (value: KnowledgeNoteProvenance) => {
    const mapped = validateKnowledgeNoteProvenance(remapReferences(value, maps, {}, identity.id))
    if (!mapped) throw new Error("Note source history cannot be restored safely.")
    return mapped
  }
  if (provenance) {
    output.knowledge_provenance = remapProvenance(provenance)
    output.content = retainKnowledgeNoteProvenance(note.content, { knowledge_provenance: output.knowledge_provenance })
  }
  if (note.pendingKnowledgeProvenance) output.pendingKnowledgeProvenance = remapProvenance(note.pendingKnowledgeProvenance)
  for (const key of ["version", "pendingNoteWriteKey", "knowledge_provenance_state", "knowledge_provenance_version", "knowledge_provenance_hash", "knowledge_provenance_reconciliation"] as const) delete output[key]
  output.keywords = [...new Set([...(note.keywords || []).filter(keyword => !keyword.toLowerCase().startsWith("workspace:")), identity.tag, `workspace:${identity.id}`])]
  return output
}

/** Requires authenticated restore maps; archive-supplied or coincident numeric IDs are never accepted as a fallback. */
export const remapPortableWorkspace = (
  bundle: WorkspaceExportBundle,
  maps: VerifiedResearchImportMaps,
  identity: PortableWorkspaceIdentity,
  makeId: () => string = () => crypto.randomUUID()
): WorkspaceExportBundle => {
  if (!record(maps?.media) || !record(maps?.notes)) throw new Error("Verified import mappings are required.")
  const output = clone(bundle)
  const snapshot = output.workspace.snapshot
  const sourceIds = Object.fromEntries(snapshot.sources.map(source => [source.id, makeId()]))
  const artifactIds = Object.fromEntries(snapshot.generatedArtifacts.map(artifact => [artifact.id, makeId()]))
  const folderIds = Object.fromEntries((snapshot.sourceFolders || []).map(folder => [folder.id, makeId()]))
  for (const source of snapshot.sources) {
    // A version-pinned web capture needs a verified version mapping, which Chatbooks does not provide.
    if (source.webCapture) throw new Error("Version-pinned web captures cannot be migrated by this research pack. Export their saved text separately.")
    source.mediaId = mappedMedia(source.mediaId, maps)
    source.id = sourceIds[source.id]
    if (source.knowledgeQaEvidence) source.knowledgeQaEvidence = remapReferences(source.knowledgeQaEvidence, maps, sourceIds, identity.id) as typeof source.knowledgeQaEvidence
    delete source.statusDetails
    delete source.statusMessage
    delete source.readiness
    delete source.captureOwnerScope
    delete source.thumbnailUrl
    delete source.reviewedByUserId
    source.status = "ready"
  }
  snapshot.selectedSourceIds = snapshot.selectedSourceIds.map(id => sourceIds[id]).filter(Boolean)
  if (snapshot.sourceAnnotations) snapshot.sourceAnnotations = Object.fromEntries(Object.entries(snapshot.sourceAnnotations).map(([id, value]) => {
    if (!sourceIds[id]) throw new Error("Annotations reference a source outside this research pack.")
    return [sourceIds[id], value]
  }))
  snapshot.sourceFolders = (snapshot.sourceFolders || []).map(folder => ({ ...folder, id: folderIds[folder.id], workspaceId: identity.id, parentFolderId: folder.parentFolderId ? folderIds[folder.parentFolderId] : null }))
  snapshot.sourceFolderMemberships = (snapshot.sourceFolderMemberships || []).map(row => ({ ...row, sourceId: sourceIds[row.sourceId], folderId: folderIds[row.folderId] }))
  snapshot.selectedSourceFolderIds = (snapshot.selectedSourceFolderIds || []).map(id => folderIds[id]).filter(Boolean)
  snapshot.activeFolderId = snapshot.activeFolderId ? folderIds[snapshot.activeFolderId] || null : null
  snapshot.generatedArtifacts = snapshot.generatedArtifacts.map(artifact => {
    const hydrated = { ...readWorkspaceArtifactClientPayload(artifact.versionMetadata), ...artifact }
    const mapped = remapReferences(hydrated, maps, sourceIds, identity.id) as typeof artifact
    mapped.id = artifactIds[artifact.id]
    for (const key of ["workspaceArtifactId", "workspaceArtifactVersion", "serverId", "ownerScope", "ownerId", "projectId", "taskId", "sourceCollectionId", "audioUrl", "presentationId", "presentationVersion", "exportRefs"] as const) delete mapped[key]
    for (const key of ["rootArtifactId", "artifactVersionId", "previousVersionId"] as const) {
      if (mapped[key]) mapped[key] = artifactIds[mapped[key]!] || undefined
    }
    mapped.producerMetadata = { origin: "research_pack_import", importedProducer: mapped.producerMetadata || {} }
    if (mapped.status === "generating") {
      mapped.status = "failed"
      mapped.errorMessage = "Imported checkpoint. The original generation job is not connected to this server."
    }
    // Canonical persistence rebuilds this client projection from the remapped artifact.
    if (mapped.versionMetadata) delete mapped.versionMetadata.workspaceClient
    return mapped
  })
  snapshot.currentNote = remapPortableNote(snapshot.currentNote, maps, identity)
  if (output.workspace.chatSession) {
    const session = remapReferences(output.workspace.chatSession, maps, sourceIds, identity.id) as typeof output.workspace.chatSession
    session.messages = session.messages.map(message => ({ ...message, id: makeId() }))
    output.workspace.chatSession = sanitizeImportedChatSession(session)
  }
  output.workspace.name = snapshot.workspaceName = identity.name
  output.workspace.tag = snapshot.workspaceTag = identity.tag
  delete output.workspace.collectionId
  return output
}
