import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { spawn } from 'node:child_process';
const root=process.cwd();
const privateDir=path.join(root,'.tmp/fresh-uat-recovery-20260916');
const cfg=JSON.parse(fs.readFileSync(path.join(privateDir,'postgres-private.json')));
const fixtureDatabase='tldw_uat_'+createHash('sha256').update(process.env.TLDW_UAT_EVIDENCE_LABEL||'pg-fixture-validation').digest('hex').slice(0,12);
const dsn=`postgresql://${cfg.user}:${cfg.password}@${cfg.host}:${cfg.port}/${fixtureDatabase}`;
const env={...process.env,TEST_DATABASE_URL:dsn,POSTGRES_TEST_DSN:dsn,JOBS_DB_URL:dsn,TLDW_TEST_POSTGRES_REQUIRED:'1',TLDW_TEST_NO_DOCKER:'1',TLDW_TEST_PG_CONTAINER_NAME:cfg.container,TLDW_TEST_PG_ALT_PORT:String(cfg.port)};
delete env.JOBS_DB_URL;
const args=['-m','pytest',...process.argv.slice(2)];
const label=process.env.TLDW_UAT_EVIDENCE_LABEL||'pg-recovery-validation';
if(!/^[a-z0-9-]+$/.test(label))throw Error('Invalid evidence label');
const log=path.join(privateDir,label+'.private.log');
const fd=fs.openSync(log,'w',0o600);
fs.writeFileSync(path.join(privateDir,label+'-command.json'),JSON.stringify({at:new Date().toISOString(),command:['.venv/bin/python',...args],postgresRequired:true,fixtureDatabase,fixtureProvisioning:true,reusesRunningOwnedContainer:cfg.container,dockerAutostart:false,port:cfg.port},null,2)+'\n');
const child=spawn(path.join(root,'.venv/bin/python'),args,{cwd:root,env,stdio:['ignore',fd,fd]});
child.on('exit',(code,signal)=>{fs.closeSync(fd);let text=fs.readFileSync(log,'utf8');for(const value of [dsn,cfg.password])if(value)text=text.split(value).join('[REDACTED]');const redacted=path.join(privateDir,label+'.redacted.log');fs.writeFileSync(redacted,text);console.log(JSON.stringify({code,signal,redactedLog:redacted}));console.log(text.split('\n').slice(-12).join('\n'));process.exitCode=code??1;});
