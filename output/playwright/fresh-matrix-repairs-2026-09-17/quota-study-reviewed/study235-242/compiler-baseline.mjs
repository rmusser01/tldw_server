import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
const root=process.cwd();
const require=createRequire(path.join(root,'apps/tldw-frontend/package.json'));
const ts=require('typescript');
const files=['apps/packages/ui/src/components/Flashcards/tabs/ReviewTab.tsx','apps/packages/ui/src/assets/locale/en/option.json','apps/packages/ui/src/components/Flashcards/tabs/__tests__/ReviewTab.rerate.test.tsx','apps/packages/ui/src/components/Flashcards/tabs/__tests__/ReviewTab.cram-mode.test.tsx','apps/packages/ui/src/components/Flashcards/tabs/__tests__/ReviewTab.cram-completion.test.tsx'];
const previous=new Map(files.map(file=>[path.join(root,file),execFileSync('git',['show',`HEAD:${file}`],{encoding:'utf8',maxBuffer:4*1024*1024})]));
const config=path.join(root,'apps/tldw-frontend/tsconfig.json');
const read=ts.readConfigFile(config,ts.sys.readFile);
const parsed=ts.parseJsonConfigFileContent(read.config,ts.sys,path.dirname(config));
const options={...parsed.options,incremental:false,noEmit:true};
const host=ts.createCompilerHost(options);
const originalRead=host.readFile;
if (!process.argv.includes("--current")) host.readFile=file=>previous.get(path.resolve(file))??originalRead(file);
const program=ts.createProgram(parsed.fileNames,options,host);
const diagnostics=ts.getPreEmitDiagnostics(program).map(d=>({file:d.file?path.relative(root,d.file.fileName):'',code:d.code,message:ts.flattenDiagnosticMessageText(d.messageText,'\n')}));
fs.writeFileSync('.tmp/uat-repairs-231-246/study235-242/tsc-fresh-' + (process.argv.includes('--current') ? 'current' : 'baseline') + '.json',JSON.stringify(diagnostics,null,2)+'\n');
console.log(JSON.stringify({count:diagnostics.length,baseline:'HEAD source with current installed dependencies; compiler read overlay only'}));
